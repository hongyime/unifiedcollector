"""Cookie sync endpoint for the ig_ingest bridge.

Extracted from ``__init__.py`` per PERF-003 step 9
(``docs/plans/perf-file-splits.md`` §4B).

The extension POSTs its live logged-in cookies here so the headless
Instagram collector can pick them up as a Netscape ``cookies.txt`` — this
prevents the headless path from running with a stale session and racking
up 401s that look bot-like.
"""
import logging
import os
import re
from collections.abc import Iterable
from pathlib import Path
from typing import Any

from aiohttp import web

from .cors import _cors


logger = logging.getLogger("social_ingest")


def _sanitize_account(value: object) -> str:
    cleaned = re.sub(r"[^A-Za-z0-9_.-]", "_", str(value or "extension_live"))[:60]
    # Strip leading dots so the result can never be "." or ".." (path traversal).
    cleaned = cleaned.lstrip(".") or "extension_live"
    return cleaned


def _netscape_cookie_lines(cookies: Iterable[Any], default_domain: str) -> list[str]:
    lines = ["# Netscape HTTP Cookie File", "# generated by the UnifiedCollector extension", ""]
    for c in cookies:
        if not isinstance(c, dict) or not c.get("name"):
            continue
        domain = c.get("domain") or default_domain
        inc_sub = "TRUE" if domain.startswith(".") else "FALSE"
        path = c.get("path") or "/"
        secure = "TRUE" if c.get("secure") else "FALSE"
        expiry = int(c.get("expirationDate") or 0)
        lines.append(f"{domain}\t{inc_sub}\t{path}\t{secure}\t{expiry}\t{c['name']}\t{c.get('value','')}")
    return lines


def _write_cookie_jar(
    directory: Path,
    filename: str,
    cookies: Iterable[Any],
    default_domain: str,
) -> None:
    # Defense in depth against path traversal: the filename is derived from
    # request-supplied account names, so pin it to a single safe component
    # inside the fixed base directory.
    safe_name = os.path.basename(filename)
    if not safe_name or safe_name in (".", ".."):
        raise ValueError(f"refusing unsafe cookie filename: {filename!r}")
    base = directory.resolve()
    base.mkdir(parents=True, exist_ok=True)
    target = base / safe_name
    if target.parent != base:
        raise ValueError(f"cookie filename escapes base directory: {filename!r}")
    tmp = base / (safe_name + ".tmp")
    tmp.write_text("\n".join(_netscape_cookie_lines(cookies, default_domain)) + "\n")
    os.replace(tmp, target)


async def cookies_handler(request):
    """Self-healing sessions: extension pushes live logged-in cookies for headless replay."""
    from . import CREDENTIALS_ROOT, _norm_platform, _safe_json

    body = await _safe_json(request)
    platform = _norm_platform(body.get("platform"))
    if platform not in ("instagram", "strava"):
        return _cors(web.json_response({"ok": False, "reason": "unsupported"}))
    cookies = body.get("cookies") or []
    have = {c.get("name") for c in cookies if isinstance(c, dict)}
    session_cookie = "sessionid" if platform == "instagram" else "_strava4_session"
    if session_cookie not in have:  # not logged in — don't clobber a good file with junk
        return _cors(web.json_response({"ok": False, "reason": "no sessionid"}))
    account = _sanitize_account(body.get("account"))
    try:
        if platform == "instagram":
            directory = Path(CREDENTIALS_ROOT) / "instagram"
            filename = account + ".txt"
            default_domain = ".instagram.com"
        else:
            directory = Path(CREDENTIALS_ROOT) / "strava"
            filename = "strava_" + account + ".txt"
            default_domain = ".strava.com"
        _write_cookie_jar(directory, filename, cookies, default_domain)
        if platform == "instagram":
            logger.info("cookies: wrote live session for instagram/%s (%d cookies)", account, len(cookies))
        else:
            logger.info("cookies: wrote live session for strava/%s (%d cookies)", account, len(cookies))
    except Exception as e:
        logger.warning("cookies write failed: %s", e)
        return _cors(web.json_response({"ok": False, "error": str(e)}, status=500))
    return _cors(web.json_response({"ok": True, "account": account}))
