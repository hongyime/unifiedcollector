class UserAgentPool:
    """Provides realistic browser user-agent strings.

    ``get_random()`` returns a random UA.
    ``get_for_domain(domain)`` returns a deterministic-per-session UA that
    stays consistent for the same domain within a single process lifetime,
    avoiding mid-session fingerprint changes that anti-bot systems detect.
    """

    def __init__(self):
        self._domain_map: dict[str, str] = {}
        self._lock = threading.Lock()
        self._session_salt = random.randbytes(8).hex()

    def get_random(self) -> str:
        return random.choice(_AGENTS)

    def get_for_domain(self, domain: str) -> str:
        with self._lock:
            if domain in self._domain_map:
                return self._domain_map[domain]
            key = f"{self._session_salt}:{domain}"
            idx = int(hashlib.md5(key.encode()).hexdigest()[:8], 16) % len(_AGENTS)
            ua = _AGENTS[idx]
            self._domain_map[domain] = ua
            return ua

    def get_all(self) -> list[str]:
        return list(_AGENTS)
