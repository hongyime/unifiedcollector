import json

import pytest

from src.bridges import ig_ingest
from src.bridges.ig_ingest.cookies import cookies_handler


class _FakeRequest(dict):
    def __init__(self, body):
        super().__init__()
        self._body = body

    async def json(self):
        return self._body


def _payload(response):
    return json.loads(response.text)


@pytest.mark.asyncio
async def test_strava_cookie_sync_writes_discoverable_netscape_jar(tmp_path, monkeypatch):
    monkeypatch.setattr(ig_ingest, "CREDENTIALS_ROOT", str(tmp_path))
    response = await cookies_handler(_FakeRequest({
        "platform": "strava",
        "account": "athlete/123",
        "cookies": [{
            "name": "_strava4_session",
            "value": "synthetic-session",
            "secure": True,
            "expirationDate": 12345.9,
        }],
    }))

    jar = tmp_path / "strava" / "strava_athlete_123.txt"
    assert response.status == 200
    assert _payload(response) == {"ok": True, "account": "athlete_123"}
    assert jar.read_text().splitlines() == [
        "# Netscape HTTP Cookie File",
        "# generated by the UnifiedCollector extension",
        "",
        ".strava.com\tTRUE\t/\tTRUE\t12345\t_strava4_session\tsynthetic-session",
    ]


@pytest.mark.asyncio
async def test_strava_cookie_sync_without_session_does_not_clobber_jar(tmp_path, monkeypatch):
    monkeypatch.setattr(ig_ingest, "CREDENTIALS_ROOT", str(tmp_path))
    jar = tmp_path / "strava" / "strava_keep.txt"
    jar.parent.mkdir(parents=True)
    jar.write_text("existing jar\n")

    response = await cookies_handler(_FakeRequest({
        "platform": "strava",
        "account": "keep",
        "cookies": [{"name": "other", "value": "synthetic"}],
    }))

    assert _payload(response) == {"ok": False, "reason": "no sessionid"}
    assert jar.read_text() == "existing jar\n"


